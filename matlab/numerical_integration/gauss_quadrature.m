clear
syms x

%parameters to modify
f(x) = exp(-x^2); %function to integrate
a = 1; %integrate from a to b
b= 1.5;
no_points = 2; %number of interpolation points

%algorithm parameters
%index is number_of points
ci = {[1,1],
    [0.5555555555555556, 0.8888888888888888,0.5555555555555556],
    [0.3478548451374538, 0.6521451548625461, 0.6521451548625461, 0.3478548451374538],
    [0.2369268850561891, 0.4786286704993665, 0.5688888888888889, 0.4786286704993665, 0.2369268850561891]
};

xi = {[-0.5773502691896257,+0.5773502691896257],
    [-0.7745966692414834, 0, +0.7745966692414834],
    [-0.8611363115940526, -0.3399810435848563, +0.3399810435848563, +0.8611363115940526],
    [-0.9061798459386640, -0.5384693101056831, 0, +0.5384693101056831, +0.9061798459386640]
};
g(x) = f(((b-a)*x+b+a)/2)*(b-a)/2;

%algorithm
answer = 0;
for i=1:1:no_points
    answer = answer+ci{no_points-1}(i)*g(xi{no_points-1}(i));
end
fprintf("The answer is %.12f\n",answer);